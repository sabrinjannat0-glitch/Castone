let currentLang = "en";
try {
  if (typeof localStorage !== "undefined") {
    currentLang = localStorage.getItem("ksu_lang") || "en";
  }
} catch (e) {
  currentLang = "en";
}
if (!translations[currentLang]) {
  currentLang = "en";
}

const listeners = [];

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  try {
    if (typeof localStorage !== "undefined") {
      localStorage.setItem("ksu_lang", lang);
    }
  } catch (e) {}
  listeners.forEach((fn) => fn(currentLang));
}

export function onLangChange(fn) {
  listeners.push(fn);
}

export function t(key, params = {}) {
  const dict = translations[currentLang] || translations.en;
  let text = dict[key] !== undefined ? dict[key] : translations.en[key] !== undefined ? translations.en[key] : key;
  if (typeof text === "string") {
    Object.keys(params).forEach((k) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), params[k]);
    });
  }
  return text;
}

export function getTaskLabel(taskId) {
  const dict = translations[currentLang] || translations.en;
  if (dict.tasks && dict.tasks[taskId]) {
    return dict.tasks[taskId];
  }
  return translations.en.tasks[taskId] || taskId;
}
